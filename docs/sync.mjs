#!/usr/bin/env node
// Refreshes the docs site from the skill. GitHub Pages serves only docs/, so the runtime and themes are
// copied in, the theme picker's list is generated from themes/omarchy.json, and the credits and bridge
// sections are rendered into their pages. No dependencies: `node docs/sync.mjs`.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const docs = dirname(fileURLToPath(import.meta.url));
const root = join(docs, "..");
const vendor = join(docs, "vendor");
mkdirSync(vendor, { recursive: true });

const copies = [
  ["assets/runtime/fs-runtime.js", "fs-runtime.js"],
  ["themes/base.css", "base.css"],
  ["themes/default.css", "default.css"],
  ["themes/notebook.css", "notebook.css"],
  ["themes/omarchy.css", "omarchy.css"],
];
for (const [from, to] of copies) {
  copyFileSync(join(root, from), join(vendor, to));
  console.log(`copied  ${from} -> docs/vendor/${to}`);
}

// Theme list for the picker and the themes page. `attr` is the data-fs-theme value that shows the theme on
// one element (swatches, plates); the picker applies Default through data-fs-mode instead.
const omarchy = JSON.parse(readFileSync(join(root, "themes/omarchy.json"), "utf8"));
const themes = [
  { id: "default-light", attr: "default-light", name: "Default Light", mode: "light", family: "default" },
  { id: "default", attr: "default", name: "Default", mode: "dark", family: "default" },
  { id: "notebook-light", attr: "notebook-light", name: "Notebook Light", mode: "light", family: "notebook" },
  { id: "notebook", attr: "notebook", name: "Notebook", mode: "dark", family: "notebook" },
  ...Object.entries(omarchy.themes).map(([id, t]) => ({ id, attr: id, name: t.name, mode: t.mode, family: "omarchy" })),
];
writeFileSync(
  join(vendor, "themes.js"),
  `/* Generated by docs/sync.mjs from themes/omarchy.json (Omarchy ${String(omarchy.commit).slice(0, 7)}). Do not edit. */\nwindow.AV_THEMES = ${JSON.stringify(themes, null, 1)};\n`,
);
console.log(`wrote   docs/vendor/themes.js (${themes.length} themes)`);

// Replace the text between <!-- name:start --> and <!-- name:end --> in a page.
function inject(page, name, html) {
  const file = join(docs, page);
  const source = readFileSync(file, "utf8");
  const pattern = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!pattern.test(source)) throw new Error(`docs/${page}: missing <!-- ${name}:start --> / <!-- ${name}:end --> markers`);
  writeFileSync(file, source.replace(pattern, (_, a, b) => `${a}\n${html}\n${b}`));
  console.log(`updated docs/${page} (${name})`);
}

const escape = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Just enough Markdown for THIRD_PARTY_NOTICES.md: headings, paragraphs, bullets, bold, links, code.
function inline(text) {
  const codes = [];
  let s = escape(text).replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, href) => `<a href="${href}">${t}</a>`);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[i]}</code>`);
}
function markdown(md) {
  const out = [];
  let para = [];
  let list = null;
  const flush = () => {
    if (para.length) out.push(`<p>${inline(para.join(" "))}</p>`);
    para = [];
    if (list) out.push(`<ul>\n${list.map((li) => `  <li>${inline(li)}</li>`).join("\n")}\n</ul>`);
    list = null;
  };
  for (const line of md.split("\n")) {
    const heading = /^(#{1,3})\s+(.*)$/.exec(line);
    if (heading) {
      flush();
      // The page owns its h1, so the notices start at h2.
      const level = Math.max(2, heading[1].length);
      out.push(`<h${level}>${inline(heading[2])}</h${level}>`);
    } else if (/^\s*-\s+/.test(line)) {
      if (para.length) flush();
      list ??= [];
      list.push(line.replace(/^\s*-\s+/, ""));
    } else if (!line.trim()) flush();
    else if (list && /^\s+/.test(line)) list[list.length - 1] += ` ${line.trim()}`;
    else {
      if (list) flush();
      para.push(line.trim());
    }
  }
  flush();
  return out.join("\n");
}

const notices = readFileSync(join(root, "THIRD_PARTY_NOTICES.md"), "utf8").replace(/^# .*\n/, "");
inject("credits.html", "notices", markdown(notices));

const bridge = readFileSync(join(root, "themes/site-bridge.css"), "utf8").trim();
inject("themes.html", "bridge", `<pre><code class="language-css">${escape(bridge)}</code></pre>`);

console.log(`done    ${relative(process.cwd(), docs) || "."}`);
